#!/usr/bin/env node
// Builds everything that isn't hand-written, from skills/claude/ and CLAUDE.md:
//   skills/portable/   the same skills, Agent Skills spec fields only, agent-neutral wording
//   skills/bundled/    one self-contained file per topic, for agents that can't follow pointers
//   AGENTS.md          CLAUDE.md for other agents, plus a skill index
// Usage: node scripts/build.mjs          write the outputs
//        node scripts/build.mjs --check  exit 1 if the outputs on disk are stale

import { readFileSync, writeFileSync, readdirSync, mkdirSync, rmSync, existsSync, statSync } from 'node:fs';
import { join, dirname, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, 'skills/claude');
const PORTABLE = 'skills/portable';
const BUNDLED = 'skills/bundled';
const DESCRIPTION_LIMIT = 1024;
const COMPATIBILITY_LIMIT = 500;
const GENERATED = '<!-- Generated by scripts/build.mjs from skills/claude. Do not edit. -->';

const config = JSON.parse(readFileSync(join(ROOT, 'scripts/portable.json'), 'utf8'));
const skillNames = readdirSync(SRC).filter((n) => existsSync(join(SRC, n, 'SKILL.md'))).sort();

const fail = (message) => {
  console.error(`build: ${message}`);
  process.exit(1);
};

const applyReplacements = (text, pairs) => pairs.reduce((out, [from, to]) => out.split(from).join(to), text);

function parseSkillFile(text, name) {
  const match = text.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
  if (!match) fail(`${name}/SKILL.md has no frontmatter`);
  const fields = {};
  for (const line of match[1].split('\n')) {
    const field = line.match(/^([a-z_-]+):\s*(.*)$/);
    if (!field) fail(`${name}/SKILL.md: frontmatter line isn't "key: value" on one line: ${line.slice(0, 60)}`);
    fields[field[1]] = field[2];
  }
  return { fields, body: match[2] };
}

function portableFrontmatter(name, fields) {
  const override = config.skills[name] ?? {};
  let description = override.description ?? fields.description;
  if (!override.description && fields.when_to_use && !/\bUse when\b/.test(description)) {
    const folded = `${description} ${fields.when_to_use}`;
    if (folded.length > DESCRIPTION_LIMIT) {
      fail(`${name}: description plus when_to_use is ${folded.length} characters. Add a portable description to scripts/portable.json.`);
    }
    description = folded;
  }
  description = applyReplacements(description, config.replacements);
  if (!/\bUse when\b/i.test(description)) fail(`${name}: portable description has no "Use when" clause`);
  if (description.length > DESCRIPTION_LIMIT) fail(`${name}: portable description is ${description.length} characters (limit ${DESCRIPTION_LIMIT})`);
  const lines = [`name: ${name}`, `description: ${JSON.stringify(description)}`];
  if (override.compatibility) {
    if (override.compatibility.length > COMPATIBILITY_LIMIT) fail(`${name}: compatibility is over ${COMPATIBILITY_LIMIT} characters`);
    lines.push(`compatibility: ${JSON.stringify(override.compatibility)}`);
  }
  return { description, text: `---\n${lines.join('\n')}\n---\n` };
}

// Applies fn to every line outside fenced code blocks.
function mapProse(text, fn) {
  let fence = null;
  return text
    .split('\n')
    .map((line) => {
      const marker = line.match(/^\s*(```|~~~)/);
      if (marker) {
        if (!fence) fence = marker[1];
        else if (marker[1] === fence) fence = null;
        return line;
      }
      return fence ? line : fn(line);
    })
    .join('\n');
}

const titleOf = (body, fallback) => (body.match(/^# (.+)$/m)?.[1] ?? fallback).trim();
const dropTitle = (body) => body.replace(/^# .+\n+/m, '');
const demote = (body, levels) => mapProse(body, (line) => line.replace(/^(#{1,6}) /, (_, hashes) => `${'#'.repeat(Math.min(6, hashes.length + levels))} `));
const rewriteLinks = (body, fn) => mapProse(body, (line) => line.replace(/\]\(([^)#\s]+\.md)(#[^)]*)?\)/g, (_, path, anchor = '') => `](${fn(path)}${anchor})`));
const section = (body, levels) => demote(dropTitle(body), levels).trim();

// Finds pointers to files in other skills. Two forms are in use:
//   `other-skill/reference/file.md`
//   `other-skill` ... `reference/file.md`   (skill named earlier on the same line)
function crossReferences(text, ownSkill) {
  const found = [];
  const add = (skill, path) => {
    if (skill === ownSkill || !existsSync(join(SRC, skill, path))) return;
    if (!found.some((ref) => ref.skill === skill && ref.path === path)) found.push({ skill, path });
  };
  mapProse(text, (line) => {
    let lastSkill = null;
    for (const [, span] of line.matchAll(/`([^`]+)`/g)) {
      const direct = span.match(/^([a-z0-9-]+)\/(SKILL\.md|reference\/[a-z0-9-]+\.md)$/);
      if (direct && skillNames.includes(direct[1])) add(direct[1], direct[2]);
      else if (skillNames.includes(span)) lastSkill = span === ownSkill ? null : span;
      else if (lastSkill && /^reference\/[a-z0-9-]+\.md$/.test(span)) add(lastSkill, span);
    }
    return line;
  });
  return found;
}

const bundlePath = (path) => (path === 'SKILL.md' ? 'index.md' : path.replace(/^reference\//, ''));

function sharedDefinitions(refs, portable) {
  if (refs.length === 0) return '';
  const parts = refs.map(({ skill, path }) => {
    const source = portable.get(`${skill}/${path}`);
    // Links in the copied file are relative to its own skill. Point them at that skill's bundle.
    const body = rewriteLinks(source, (link) => `../${skill}/${link === '../SKILL.md' ? 'index.md' : bundlePath(link)}`);
    return `### From ${skill}: ${titleOf(source, path)}\n\n${section(body, 3)}`;
  });
  return `\n\n## Shared definitions\n\nWhat this file relies on from other skills, copied in so nothing needs looking up.\n\n${parts.join('\n\n')}`;
}

function build() {
  const out = new Map(); // repo-relative path -> content
  const portable = new Map(); // "skill/path" -> portable body, frontmatter stripped
  const index = [];

  for (const name of skillNames) {
    const dir = join(SRC, name);
    const { fields, body } = parseSkillFile(readFileSync(join(dir, 'SKILL.md'), 'utf8'), name);
    if (fields.name !== name) fail(`${name}: frontmatter name is "${fields.name}"`);
    const frontmatter = portableFrontmatter(name, fields);
    const skillBody = applyReplacements(body, config.replacements);
    out.set(`${PORTABLE}/${name}/SKILL.md`, frontmatter.text + skillBody);
    portable.set(`${name}/SKILL.md`, skillBody);

    const refDir = join(dir, 'reference');
    const refs = existsSync(refDir) ? readdirSync(refDir).filter((f) => f.endsWith('.md')).sort() : [];
    for (const file of refs) {
      const text = applyReplacements(readFileSync(join(refDir, file), 'utf8'), config.replacements);
      out.set(`${PORTABLE}/${name}/reference/${file}`, text);
      portable.set(`${name}/reference/${file}`, text);
    }
    index.push({ name, description: frontmatter.description, title: titleOf(skillBody, name), refs });
  }

  for (const { name, title, refs } of index) {
    const skillBody = portable.get(`${name}/SKILL.md`);
    const rules = rewriteLinks(skillBody, bundlePath);
    const indexShared = refs.length === 0 ? sharedDefinitions(crossReferences(skillBody, name), portable) : '';
    out.set(`${BUNDLED}/${name}/index.md`, `${GENERATED}\n\n# ${title}\n\n${section(rules, 0)}${indexShared}\n`);

    for (const file of refs) {
      const topic = portable.get(`${name}/reference/${file}`);
      const topicBody = rewriteLinks(topic, (link) => (link === '../SKILL.md' ? 'index.md' : link));
      const shared = sharedDefinitions(crossReferences(topic, name), portable);
      out.set(
        `${BUNDLED}/${name}/${file}`,
        `${GENERATED}\n\n# ${title}: ${titleOf(topic, file)}\n\n` +
          `Self-contained. The skill's rules, then this topic, then anything it relies on from other skills.\n\n` +
          `## Skill rules\n\n${section(rules, 1)}\n\n## Topic\n\n${section(topicBody, 1)}${shared}\n`,
      );
    }
  }

  const bundleRows = index
    .map(({ name, title, refs }) => `| ${title} | [${name}/index.md](${name}/index.md) | ${refs.map((f) => `[${f.replace(/\.md$/, '')}](${name}/${f})`).join(', ') || 'none'} |`)
    .join('\n');
  out.set(
    `${BUNDLED}/INDEX.md`,
    `${GENERATED}\n\n# Bundled Skills\n\nFor agents with no skill discovery, or that won't follow a pointer from one skill to another. ` +
      `Every topic file stands alone: the skill's rules, the topic, and the definitions it needs from other skills. Load one file, not the folder.\n\n` +
      `| Skill | Rules only | Topic files |\n| --- | --- | --- |\n${bundleRows}\n`,
  );

  const firstSentence = (text) => text.split(/(?<=\.)\s/)[0];
  const skillRows = index.map(({ name, description }) => `| \`${name}\` | ${firstSentence(description).replace(/\|/g, '/')} | \`${name}/SKILL.md\` |`).join('\n');
  const agents = applyReplacements(readFileSync(join(ROOT, 'CLAUDE.md'), 'utf8'), config.agents.replacements);
  for (const [from] of config.agents.replacements) {
    if (!readFileSync(join(ROOT, 'CLAUDE.md'), 'utf8').includes(from)) fail(`CLAUDE.md no longer contains: ${from}`);
  }
  out.set(
    'AGENTS.md',
    `${GENERATED.replace('skills/claude', 'CLAUDE.md')}\n\n${agents.trimEnd()}\n\n# Skill Index\n\n` +
      `If your agent finds skills by their descriptions, skip this. If it doesn't, this is the routing table. Read the file before you work on what it covers. ` +
      `Paths are relative to the skills directory (\`skills/portable/\` in the source repo). ` +
      `If you can't follow pointers between skills, use \`skills/bundled/\` instead: every file there stands alone.\n\n` +
      `| Skill | What it is | File |\n| --- | --- | --- |\n${skillRows}\n`,
  );

  return out;
}

function listFiles(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir).flatMap((entry) => {
    const path = join(dir, entry);
    if (entry === '.DS_Store') return [];
    return statSync(path).isDirectory() ? listFiles(path) : [relative(ROOT, path)];
  });
}

const outputs = build();
const onDisk = [...listFiles(join(ROOT, PORTABLE)), ...listFiles(join(ROOT, BUNDLED))];

if (process.argv.includes('--check')) {
  const stale = [...outputs].filter(([path, content]) => !existsSync(join(ROOT, path)) || readFileSync(join(ROOT, path), 'utf8') !== content).map(([path]) => path);
  const extra = onDisk.filter((path) => !outputs.has(path));
  if (stale.length || extra.length) {
    for (const path of stale) console.error(`stale: ${path}`);
    for (const path of extra) console.error(`not generated: ${path}`);
    fail('generated files are out of date. Run node scripts/build.mjs and commit the result.');
  }
  console.log(`build: ${outputs.size} generated files are current`);
} else {
  for (const path of onDisk) if (!outputs.has(path)) rmSync(join(ROOT, path));
  for (const [path, content] of outputs) {
    mkdirSync(dirname(join(ROOT, path)), { recursive: true });
    writeFileSync(join(ROOT, path), content);
  }
  console.log(`build: wrote ${outputs.size} files (${skillNames.length} skills)`);
}
